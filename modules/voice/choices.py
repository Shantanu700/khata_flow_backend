from enum import StrEnum

from django.db.models import TextChoices


class InputMode(TextChoices):
    AUDIO = "AUDIO", "Audio"
    TEXT = "TEXT", "Text"


class CommandStatus(TextChoices):
    RECEIVED = "RECEIVED", "Received"
    TRANSCRIBED = "TRANSCRIBED", "Transcribed"
    PARSED = "PARSED", "Parsed"
    NEEDS_CLARIFICATION = "NEEDS_CLARIFICATION", "Needs clarification"
    COMMITTED = "COMMITTED", "Committed"
    ANSWERED = "ANSWERED", "Answered"
    FAILED = "FAILED", "Failed"
    CANCELLED = "CANCELLED", "Cancelled"


class Intent(StrEnum):
    ADD_CREDIT = "ADD_CREDIT"
    RECORD_PAYMENT = "RECORD_PAYMENT"
    STOCK_IN = "STOCK_IN"
    STOCK_OUT = "STOCK_OUT"
    MARK_ATTENDANCE = "MARK_ATTENDANCE"
    STAFF_ADVANCE = "STAFF_ADVANCE"
    SALARY_PAID = "SALARY_PAID"
    QUERY_CUSTOMER_BALANCE = "QUERY_CUSTOMER_BALANCE"
    QUERY_TOTAL_OUTSTANDING = "QUERY_TOTAL_OUTSTANDING"
    QUERY_LOW_STOCK = "QUERY_LOW_STOCK"
    QUERY_STOCK_LEVEL = "QUERY_STOCK_LEVEL"
    QUERY_STAFF_DUE = "QUERY_STAFF_DUE"
    QUERY_STAFF_LIST = "QUERY_STAFF_LIST"
    QUERY_ATTENDANCE_TODAY = "QUERY_ATTENDANCE_TODAY"
    QUERY_CUSTOMER_COUNT = "QUERY_CUSTOMER_COUNT"
    QUERY_DEBTOR_LIST = "QUERY_DEBTOR_LIST"
    QUERY_STOCK_LIST = "QUERY_STOCK_LIST"
    QUERY_CREDIT_GIVEN = "QUERY_CREDIT_GIVEN"
    QUERY_PAYMENTS_RECEIVED = "QUERY_PAYMENTS_RECEIVED"
    QUERY_STAFF_PAID = "QUERY_STAFF_PAID"
    QUERY_STOCK_MOVEMENT = "QUERY_STOCK_MOVEMENT"
    ADD_CUSTOMER = "ADD_CUSTOMER"
    ADD_STAFF = "ADD_STAFF"
    ADD_PRODUCT = "ADD_PRODUCT"
    UNDO_LAST = "UNDO_LAST"
    UNKNOWN = "UNKNOWN"


class Period(StrEnum):
    TODAY = "TODAY"
    YESTERDAY = "YESTERDAY"
    THIS_WEEK = "THIS_WEEK"
    LAST_WEEK = "LAST_WEEK"
    THIS_MONTH = "THIS_MONTH"
    LAST_MONTH = "LAST_MONTH"
    ALL = "ALL"


CUSTOMER_INTENTS = {Intent.ADD_CREDIT, Intent.RECORD_PAYMENT, Intent.QUERY_CUSTOMER_BALANCE}
STAFF_INTENTS = {Intent.MARK_ATTENDANCE, Intent.STAFF_ADVANCE, Intent.SALARY_PAID, Intent.QUERY_STAFF_DUE}
PRODUCT_INTENTS = {Intent.STOCK_IN, Intent.STOCK_OUT, Intent.QUERY_STOCK_LEVEL}
# Totals over a period: a name narrows them to one party or product, none means the whole shop.
OPTIONAL_CUSTOMER_INTENTS = {Intent.QUERY_CREDIT_GIVEN, Intent.QUERY_PAYMENTS_RECEIVED}
OPTIONAL_STAFF_INTENTS = {Intent.QUERY_STAFF_PAID}
OPTIONAL_PRODUCT_INTENTS = {Intent.QUERY_STOCK_MOVEMENT}
